// 店舗とお客様の間の利用規約。
//
// 運営(the合同会社)がひな形として提供し、導入店はこれを使う — 店舗ごとに
// 文面を用意させると内容が揃わず、法定表示の抜けにも気づけないため
// (2026-08-06決定)。文中に運営やPicoPayの名前は一切出さない。あくまで
// 「当店」がお客様に向けて出すものとして書く。
//
// 同じ内容が申込時にAI Console側で店舗情報を差し込んだ紙としても出力され、
// そちらはお客様のサインをもらって店舗が保管する。アプリの同意チェックと
// 紙のサインで入り口を二重にしておく狙い。
//
// 店舗ごとに変わる箇所(店舗名・有効期限など)は storeSettings から差し込む。
export function buildTerms(storeSettings = {}) {
  const storeName = storeSettings.storeName || "当店";
  const expiry =
    storeSettings.expiryPolicyText ||
    (storeSettings.depositExpiryEnabled
      ? `最終ご来店日から${storeSettings.depositExpiryYears || 1}年`
      : null);

  return [
    {
      body: `本規約は、${storeName}(以下「当店」)が提供するプリペイド決済サービス(以下「本サービス」)のご利用に関する規約です。`,
    },
    {
      title: "第1条(本サービスの内容)",
      body:
        "1. お客様は、当店店頭にてQRコードを用いたチャージおよび商品代金のお支払い(以下「決済」)をご利用いただけます。\n" +
        "2. 当店の設定により、入金ボーナス・購入ポイント・入金ガチャ・お友達紹介ポイント・天気連動ボーナス等の特典を付与する場合があります。特典の内容・還元率・付与条件は当店が定めます。",
    },
    {
      title: "第2条(会員登録)",
      body: "お客様は、本規約への同意と、当店が定める方法による登録手続きを行うことで会員登録が完了します。電話番号の変更、機種変更等による再発行の際も、当店所定の手続きが必要です。",
    },
    {
      title: "第3条(残高等の有効期限)",
      body:
        "1. ポイントの有効期限は、当店が個別に定めます。\n" +
        (expiry
          ? `2. チャージ残高(預かり金)は、${expiry}を経過した場合に失効します。失効が近づいた場合、事前にお客様の画面にてお知らせします。`
          : "2. チャージ残高(預かり金)の有効期限は、現在設定しておりません。設定する場合は、事前にお客様の画面にてお知らせします。"),
    },
    {
      title: "第4条(返金)",
      body: "残高等の返金に関するご要望は、当店までお申し出ください。返金の可否・条件・手続きは当店が定めます。",
    },
    {
      title: "第5条(本サービスの終了)",
      body:
        "1. 当店が本サービスの提供を終了する場合、決済・チャージ等のご利用ができなくなり、その後、本サービスを一切ご利用いただけなくなります。\n" +
        "2. サービス終了前には、画面にてその旨を予告表示します。\n" +
        "3. サービス終了後、残高等が残っている場合は当店までご確認ください。",
    },
    {
      title: "第6条(発行者情報等)",
      body: "発行者名、ご利用いただける店舗、残高等の有効期限、苦情・相談窓口については、この画面の下部に表示しています。",
    },
    {
      title: "第7条(禁止事項)",
      body:
        "お客様は、以下の行為を行ってはなりません。\n" +
        "・他人になりすましての登録・利用\n" +
        "・決済QRコードの不正な取得・転売・譲渡\n" +
        "・その他、当店が不適切と判断する行為",
    },
    {
      title: "第8条(免責事項)",
      body: "当店は、システムの不具合、通信障害等により本サービスが一時的にご利用いただけない場合がありますが、故意または重過失による場合を除き、これによりお客様に生じた損害について責任を負いません。",
    },
    {
      title: "第9条(規約の変更)",
      body: "本規約の内容は、必要に応じて変更されることがあります。変更後の規約は、この画面より随時ご確認いただけます。",
    },
    {
      title: "第10条(お問い合わせ)",
      body: "本サービスに関するお問い合わせは、当店までご連絡ください。",
    },
  ];
}
